def uc_for(number):
    if number == 1: return 'เมนูหลัก', 1, 1, 'Main.main()'
    ranges = [(2, 14), (15, 22), (23, 27), (28, 32), (33, 39), (40, 42), (43, 51), (52, 56)]
    for uc, (first, last) in enumerate(ranges, 1):
        if first <= number <= last:
            return f'UC{uc:02d}', number - first + 1, last - first + 1, f'Main.uc{uc:02d}()'
    raise AssertionError(number)

def simplify_terminal(text):
    text = unescape(unescape(text))
    clean = []
    for raw in text.splitlines():
        line = raw.rstrip()
        if re.fullmatch(r'\s*\+[=\-]+\+\s*', line):
            clean.append('=' * 72 if '=' in line else '-' * 72)
            continue
        if line.lstrip().startswith('|'):
            line = line.lstrip()[1:]
            if line.rstrip().endswith('|'):
                line = line.rstrip()[:-1]
            line = line.strip()
        line = line.replace('|', ' - ')
        clean.append(line)
    return '\n'.join(clean)

